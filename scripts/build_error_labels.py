"""Hand-labelled ground truth for Razorpay's payment error taxonomy.

Run:  python scripts/build_error_labels.py   ->  evals/error_labels.json

Every code in Razorpay's published xlsx is labelled here by hand, once. The
labels are the ground truth the classification eval in §4.1 scores against,
so they are checked into the repo as data rather than regenerated by a model.

Why an LLM is used at all, given this file exists: the deterministic cache in
classify.py answers every code that appears here without an API call. The
LLM's real job is the code it has NEVER seen -- gateways emit codes outside
the published taxonomy and new ones appear over time. That is why the eval
holds out CODES rather than rows, and why the headline number is generalisation
to unseen codes rather than lookup accuracy.

Label definitions
-----------------
soft_decline  temporary, customer-side or limit-related; the same payment
              could succeed later without anything being changed
hard_decline  permanent for this instrument or configuration; retrying the
              identical request cannot work
technical     infrastructure failed at bank, gateway, PSP or network
auth_failure  the customer failed or abandoned authentication

`recoverable` is deliberately NOT a restatement of the class. It asks whether
an agent acting alone can plausibly convert this payment. Auth failures are
recoverable by the CUSTOMER but not by the agent, so they are False.
"""

