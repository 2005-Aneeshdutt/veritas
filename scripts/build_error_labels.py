def load_taxonomy() -> dict[str, dict[str, str]]:
    ws = openpyxl.load_workbook(XLSX, read_only=True).worksheets[0]
    rows = [r for r in ws.iter_rows(values_only=True) if r and r[0] and str(r[0]).strip()]
    out: dict[str, dict[str, str]] = {}
    for r in rows[1:]:
        code = str(r[0]).strip()
        out.setdefault(
            code,
            {
                "explanation": str(r[1] or "").strip(),
                "next_steps": str(r[2] or "").strip(),
            },
        )
    return out


def main() -> int:
    taxonomy = load_taxonomy()
    missing = sorted(set(taxonomy) - set(LABELS))
    extra = sorted(set(LABELS) - set(taxonomy))
    if missing:
        raise SystemExit(
            "%d code(s) in the xlsx are unlabelled -- label them before the "
            "eval can run:\n  %s" % (len(missing), "\n  ".join(missing))
        )
    if extra:
        print("WARN  %d labelled code(s) no longer in the xlsx: %s" % (len(extra), extra))

    records = []
    for code, meta in sorted(taxonomy.items()):
        cls, recoverable = LABELS[code]
        records.append(
            {
                "code": code,
                "explanation": meta["explanation"],
                "next_steps": meta["next_steps"],
                "category": cls,
                "recoverable": recoverable,
            }
        )

    counts: dict[str, int] = {}
    for r in records:
        counts[r["category"]] = counts.get(r["category"], 0) + 1

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        json.dumps(
            {
                "source": "data/razorpay/payment_error_reasons.xlsx",
                "n_codes": len(records),
                "class_support": counts,
                "labels": records,
            },
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )
    print("wrote %s" % OUT.relative_to(ROOT))
    print("  %d codes" % len(records))
    for k in sorted(counts, key=lambda k: -counts[k]):
        print("  %-14s %3d  (%4.1f%%)" % (k, counts[k], 100 * counts[k] / len(records)))
    n_rec = sum(1 for r in records if r["recoverable"])
    print("  recoverable    %3d  (%4.1f%%)" % (n_rec, 100 * n_rec / len(records)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
